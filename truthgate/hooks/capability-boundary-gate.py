def _texts(turn):
    out = []
    for m in turn:
        if m.get("type") != "assistant":
            continue
        c = (m.get("message") or {}).get("content")
        if isinstance(c, str):
            out.append(c)
            continue
        for it in c or []:
            if isinstance(it, dict) and it.get("type") == "text":
                out.append(it.get("text") or "")
    return "\n".join(out)


